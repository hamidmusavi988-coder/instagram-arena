import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
await mkdir('artifacts', { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const errors = [];
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto('http://127.0.0.1:3000', { waitUntil: 'domcontentloaded' });
await page.waitForSelector('.post-card');
await page.waitForTimeout(1800);
await page.screenshot({ path: 'artifacts/desktop.png', fullPage: false });
console.log('Desktop:', await page.evaluate(() => ({ width: innerWidth, body: document.documentElement.scrollWidth, brokenImages: [...document.images].filter(i => !i.complete || i.naturalWidth === 0).map(i => i.src) })));
await page.locator('.main-nav .nav-item').filter({ hasText: 'Messages' }).click();
await page.waitForSelector('.chat-header');
await page.waitForTimeout(600);
await page.screenshot({ path: 'artifacts/messages.png', fullPage: false });
const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 1 });
const mobilePage = await mobile.newPage();
mobilePage.on('pageerror', e => errors.push(e.message));
await mobilePage.goto('http://127.0.0.1:3000', { waitUntil: 'domcontentloaded' });
await mobilePage.waitForSelector('.post-card');
await mobilePage.waitForTimeout(1300);
await mobilePage.screenshot({ path: 'artifacts/mobile.png', fullPage: false });
console.log('Mobile:', await mobilePage.evaluate(() => ({ width: innerWidth, body: document.documentElement.scrollWidth })));
console.log('Runtime errors:', errors);
await browser.close();
