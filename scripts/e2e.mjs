import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { readFile, mkdir, rm } from 'node:fs/promises';
import { Pool } from 'pg';
import { drizzle } from 'drizzle-orm/node-postgres';
import { pgTable, text } from 'drizzle-orm/pg-core';
import { inArray } from 'drizzle-orm';
const baseURL = process.env.TEST_BASE_URL || 'http://localhost:3000';
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const accountIds = [];
const conversationIds = [];
const uploads = [];
const errors = [];
const pool = new Pool({ connectionString: process.env.DATABASE_URL });
const db = drizzle(pool);
const userTable = pgTable('loop_users', { id: text('id') });
const chatTable = pgTable('loop_conversations', { id: text('id') });
let pageA;
async function get(context, resource = '') { const r = await context.request.get(`${baseURL}/api/social${resource ? `?${resource}` : ''}`); assert.equal(r.status(), 200, await r.text()); return r.json(); }
async function post(context, action, values = {}) { const r = await context.request.post(`${baseURL}/api/social`, { data: { action, ...values } }); assert.equal(r.status(), 200, await r.text()); return r.json(); }
try {
  const A = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } });
  const B = await browser.newContext({ baseURL, viewport: { width: 1280, height: 900 } });
  const stranger = await browser.newContext({ baseURL });
  const a = await get(A), b = await get(B);
  assert.notEqual(a.viewer.id, b.viewer.id);
  accountIds.push(a.viewer.id, b.viewer.id);
  conversationIds.push(...a.chats.map(c => c.id), ...b.chats.map(c => c.id));
  assert(a.posts.length >= 6 && a.people.length >= 8);
  console.log('PASS: server-backed feed and isolated preview sessions');
  const health = await A.request.get('/api/health');
  assert.equal(health.status(), 200);
  const status = await health.json();
  assert.equal(status.schema, 'ready');
  assert.equal(status.externalProviderConnections, 'not-probed');
  const unauthRealtime = await stranger.request.get('/api/realtime');
  assert.equal(unauthRealtime.status(), 401);
  const transport = await A.request.get('/api/realtime');
  assert.equal(transport.status(), 200);
  const forbiddenChannel = await A.request.post('/api/realtime', { form: { socket_id: '1.2', channel_name: `private-loop-user-${b.viewer.id}` } });
  assert.equal(forbiddenChannel.status(), 403);
  const unauthUpload = await stranger.request.get('/api/upload');
  assert.equal(unauthUpload.status(), 401);
  const invalidCloudCompletion = await A.request.post('/api/upload/complete', { data: { url: 'http://127.0.0.1/private' } });
  assert.notEqual(invalidCloudCompletion.status(), 200);
  console.log('PASS: health readiness, unauthenticated upload protection, and private realtime channel authorization');
  const nonce = Date.now();
  for (const [context, label] of [[A, 'mira'], [B, 'leo']]) {
    const r = await context.request.post('/api/auth', { data: { action: 'register', name: `QA ${label}`, username: `qa_${label}_${nonce}`, email: `${label}.${nonce}@test.invalid`, password: 'Loop-Test-Password-2026!' } });
    assert.equal(r.status(), 200, await r.text());
  }
  await B.request.post('/api/auth', { data: { action: 'logout' } });
  const wrong = await B.request.post('/api/auth', { data: { action: 'login', email: `leo.${nonce}@test.invalid`, password: 'Definitely-Wrong-Password!' } });
  assert.equal(wrong.status(), 401);
  const login = await B.request.post('/api/auth', { data: { action: 'login', email: `leo.${nonce}@test.invalid`, password: 'Loop-Test-Password-2026!' } });
  assert.equal(login.status(), 200);
  assert.equal((await get(B)).viewer.id, b.viewer.id);
  console.log('PASS: email registration, password verification, and sign-in');

  pageA = await A.newPage();
  pageA.on('pageerror', e => errors.push(e.message));
  await pageA.goto('/', { waitUntil: 'domcontentloaded' });
  await pageA.waitForSelector('.post-card');
  await pageA.waitForTimeout(500);
  const first = pageA.locator('.post-card').first();
  await first.getByRole('button', { name: 'Like post', exact: true }).click();
  await expect(first.getByRole('button', { name: 'Unlike post', exact: true })).toBeVisible();
  await first.getByRole('button', { name: 'Save post', exact: true }).click();
  await first.getByRole('textbox', { name: 'Add a comment', exact: true }).fill(`Love this coast — QA ${nonce}`);
  await first.getByRole('button', { name: 'Post', exact: true }).click();
  await expect(first.getByText(`Love this coast — QA ${nonce}`, { exact: false })).toBeVisible();
  await pageA.locator('.suggestion').first().getByRole('button', { name: 'Follow', exact: true }).click();
  await pageA.reload({ waitUntil: 'domcontentloaded' });
  const persisted = await get(A);
  const coast = persisted.posts.find(p => p.id === 'coastal-daydream');
  assert(coast.liked && coast.saved && coast.comments.some(c => c.text.includes(String(nonce))));
  assert(persisted.people.find(p => p.id === 'mia').following);
  await pageA.locator('.space-nav').getByRole('button', { name: 'Saved', exact: true }).click();
  await expect(pageA.locator('.post-card')).toHaveCount(1);
  console.log('PASS: UI likes, saves, comments, follows, and reload persistence');

  await pageA.getByRole('textbox', { name: 'Search Loop' }).fill('olivia');
  await pageA.getByRole('textbox', { name: 'Search Loop' }).press('Enter');
  await expect(pageA.locator('.person-card').getByRole('button', { name: 'Olivia Chen', exact: true })).toBeVisible();
  await pageA.locator('.person-card').getByRole('button', { name: 'Olivia Chen', exact: true }).click();
  await expect(pageA.locator('.profile-main h2')).toHaveText('Olivia Chen');
  await pageA.locator('.sidebar-profile-main').click();
  await pageA.getByRole('button', { name: 'Edit profile', exact: true }).click();
  await pageA.getByLabel('A little about you').fill('QA profile: finding joy in the everyday.');
  await pageA.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(pageA.locator('.profile-bio')).toHaveText('QA profile: finding joy in the everyday.');
  assert.equal((await get(A)).viewer.bio, 'QA profile: finding joy in the everyday.');
  console.log('PASS: discover search, user profiles, and profile editing');

  await pageA.locator('.create-button').click();
  await pageA.locator('input[type="file"]').setInputFiles('public/images/flowers.jpg');
  await pageA.locator('.caption-field textarea').fill(`A real uploaded photo. #qa_${nonce}`);
  const uploadResponse = pageA.waitForResponse(r => r.url().endsWith('/api/upload') && r.request().method() === 'POST');
  await pageA.getByRole('button', { name: 'Share your moment', exact: true }).click();
  const uploaded = await (await uploadResponse).json(); uploads.push(uploaded.url);
  await expect(pageA.locator('.post-card').first()).toContainText('A real uploaded photo.');
  const photoPost = (await get(A)).posts.find(p => p.caption.includes(`qa_${nonce}`));
  assert(photoPost && photoPost.author.id === a.viewer.id);
  const media = await A.request.get(uploaded.url); assert.equal(media.status(), 200); assert(media.headers()['content-type'].includes('image/jpeg'));
  const videoBuffer = await readFile('artifacts/test-video.mp4');
  const videoResponse = await A.request.post('/api/upload', { multipart: { file: { name: 'ocean.mp4', mimeType: 'video/mp4', buffer: videoBuffer } } });
  assert.equal(videoResponse.status(), 200, await videoResponse.text());
  const video = await videoResponse.json(); uploads.push(video.url);
  const videoPost = (await post(A, 'post', { mediaUrl: video.url, caption: 'A real video upload for QA.' })).post;
  assert.equal(videoPost.mediaType, 'video');
  const range = await A.request.get(video.url, { headers: { Range: 'bytes=0-100' } });
  assert.equal(range.status(), 206); assert.equal((await range.body()).length, 101);
  const invalidUpload = await A.request.post('/api/upload', { multipart: { file: { name: 'not-an-image.jpg', mimeType: 'image/jpeg', buffer: Buffer.from('invalid jpeg') } } });
  assert.equal(invalidUpload.status(), 400);
  console.log('PASS: real photo/video upload, playback ranges, and file validation');

  const direct = (await post(A, 'create-chat', { userIds: [b.viewer.id] })).chat;
  conversationIds.push(direct.id);
  const pageB = await B.newPage(); pageB.on('pageerror', e => errors.push(e.message));
  await pageA.goto(`/?view=messages&chat=${direct.id}`, { waitUntil: 'domcontentloaded' });
  await pageB.goto(`/?view=messages&chat=${direct.id}`, { waitUntil: 'domcontentloaded' });
  await expect(pageA.locator('.inbox-connection')).toContainText('Connected.');
  await expect(pageB.locator('.inbox-connection')).toContainText('Connected.');
  await pageA.waitForTimeout(400);
  const liveText = `A real live hello ${nonce}`;
  await pageA.getByRole('textbox', { name: 'Write a message' }).fill(liveText);
  const started = Date.now();
  await pageA.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(pageA.locator('.message-bubble').filter({ hasText: liveText })).toBeVisible({ timeout: 1000 });
  await expect(pageB.locator('.message-bubble').filter({ hasText: liveText })).toBeVisible({ timeout: 5000 });
  console.log(`PASS: optimistic send and live delivery to another account (${Date.now() - started}ms including browser checks)`);
  await pageB.reload({ waitUntil: 'domcontentloaded' });
  await expect(pageB.locator('.message-bubble').filter({ hasText: liveText })).toBeVisible();
  const guest = await get(stranger); accountIds.push(guest.viewer.id); conversationIds.push(...guest.chats.map(c => c.id));
  const forbiddenRead = await stranger.request.get(`/api/social?resource=messages&id=${direct.id}`); assert.equal(forbiddenRead.status(), 404);
  const forbiddenSend = await stranger.request.post('/api/social', { data: { action: 'message', id: direct.id, text: 'Not allowed' } }); assert.equal(forbiddenSend.status(), 404);
  const group = (await post(A, 'create-chat', { userIds: [b.viewer.id, 'emma'], isGroup: true, name: 'QA inner circle' })).chat;
  conversationIds.push(group.id); assert(group.isGroup && group.members.length === 2);
  await post(B, 'message', { id: group.id, text: 'Hello, inner circle!' });
  assert((await get(A, `resource=messages&id=${group.id}`)).messages.some(m => m.text === 'Hello, inner circle!'));
  console.log('PASS: message persistence, group chats, and membership authorization');

  const stolenUpload = await B.request.post('/api/social', { data: { action: 'post', mediaUrl: uploaded.url, caption: 'Must be rejected.' } });
  assert.equal(stolenUpload.status(), 400);
  const bUploadResponse = await B.request.post('/api/upload', { multipart: { file: { name: 'flowers.jpg', mimeType: 'image/jpeg', buffer: await readFile('public/images/flowers.jpg') } } });
  assert.equal(bUploadResponse.status(), 200);
  const bUpload = await bUploadResponse.json(); uploads.push(bUpload.url);
  const bPost = (await post(B, 'post', { mediaUrl: bUpload.url, caption: 'A QA moment for notifications.' })).post;
  console.log('PASS: media ownership enforced between independent accounts');
  await post(A, 'like', { id: bPost.id, active: true });
  const notifications = await get(B, 'resource=notifications');
  assert(notifications.notifications.some(n => n.kind === 'like' && n.actor.id === a.viewer.id && !n.read));
  await post(B, 'read-notifications');
  assert((await get(B, 'resource=notifications')).notifications.every(n => n.read));
  const key = await get(A, 'resource=push-key'); assert(key.publicKey.length > 70);
  const worker = await A.request.get('/sw.js'); assert.equal(worker.status(), 200);
  const google = await A.request.get('/api/auth/google', { maxRedirects: 0 });
  assert([302, 307].includes(google.status()));
  console.log('PASS: activity notifications, read state, push configuration, and OAuth availability handling');
  await post(A, 'delete-post', { id: photoPost.id });
  await post(A, 'delete-post', { id: videoPost.id });
  assert(!(await get(A)).posts.some(p => p.id === photoPost.id || p.id === videoPost.id));
  assert.equal(errors.length, 0, errors.join('\n'));
  console.log('ALL END-TO-END CHECKS PASSED');
} catch (error) {
  await mkdir('artifacts', { recursive: true });
  if (pageA) await pageA.screenshot({ path: 'artifacts/e2e-failure.png', fullPage: false }).catch(() => {});
  console.error(error);
  process.exitCode = 1;
} finally {
  await browser.close();
  if (conversationIds.length) await db.delete(chatTable).where(inArray(chatTable.id, conversationIds));
  if (accountIds.length) await db.delete(userTable).where(inArray(userTable.id, accountIds));
  for (const url of uploads) await rm(`.data/uploads/${url.split('/').pop()}`, { force: true });
  await pool.end();
  console.log('Test accounts and uploaded test content cleaned up.');
}
