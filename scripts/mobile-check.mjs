import { chromium, expect } from '@playwright/test';
import { Pool } from 'pg';
import { drizzle } from 'drizzle-orm/node-postgres';
import { pgTable, text } from 'drizzle-orm/pg-core';
import { eq, inArray } from 'drizzle-orm';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const context = await browser.newContext({ baseURL: 'http://localhost:3000', viewport: { width: 390, height: 844 }, isMobile: true });
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const pool = new Pool({ connectionString: process.env.DATABASE_URL });
const db = drizzle(pool);
const users = pgTable('loop_users', { id: text('id') });
const chats = pgTable('loop_conversations', { id: text('id') });
let id;
const chatIds = [];
try {
  await page.goto('/', { waitUntil: 'domcontentloaded' });
  await page.waitForSelector('.post-card');
  await page.waitForTimeout(500);
  const initial = await (await context.request.get('/api/social')).json();
  id = initial.viewer.id; chatIds.push(...initial.chats.map(c => c.id));
  await page.locator('.search-icon').click();
  await expect(page.getByRole('textbox', { name: 'Search Loop' })).toBeFocused();
  await page.getByRole('textbox', { name: 'Search Loop' }).fill('olivia');
  await page.getByRole('textbox', { name: 'Search Loop' }).press('Enter');
  await expect(page.locator('.person-card')).toHaveCount(1);
  await page.locator('.results-heading h2').click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  console.log('PASS: accessible mobile search without overflow');
  await page.locator('.mobile-nav').getByRole('button', { name: 'Messages', exact: true }).click();
  await expect(page.locator('.conversation-sidebar')).toBeVisible();
  await page.locator('.conversation').first().click();
  await expect(page.locator('.chat-panel')).toBeVisible();
  await page.getByRole('textbox', { name: 'Write a message' }).fill('A little mobile hello.');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(page.locator('.message-bubble').filter({ hasText: 'A little mobile hello.' })).toBeVisible();
  await page.getByRole('button', { name: 'Back to inbox' }).click();
  await expect(page.locator('.conversation-sidebar')).toBeVisible();
  await page.locator('.new-group-button').click();
  await page.getByLabel('Give your circle a name').fill('QA mobile circle');
  await page.locator('.new-chat-people button').filter({ hasText: 'Mia Rose' }).click();
  await page.locator('.new-chat-people button').filter({ hasText: 'Jake Miller' }).click();
  const created = page.waitForResponse(r => r.url().endsWith('/api/social') && r.request().method() === 'POST' && r.request().postDataJSON()?.action === 'create-chat');
  await page.getByRole('button', { name: 'Create group', exact: true }).click();
  const group = (await (await created).json()).chat; chatIds.push(group.id);
  await expect(page.locator('.chat-header h2')).toHaveText('QA mobile circle');
  await expect(page.locator('.chat-header')).toContainText('3 people in your circle');
  console.log('PASS: mobile inbox, sending, back navigation, and group creation');
  await page.locator('.mobile-nav').getByRole('button', { name: 'Home', exact: true }).click();
  await page.locator('.feed-preferences').click();
  await page.getByRole('checkbox', { name: 'Photo moments' }).uncheck();
  await page.getByRole('button', { name: 'Save preferences', exact: true }).click();
  await expect(page.locator('.post-card')).toHaveCount(1);
  await page.locator('.feed-preferences').click();
  await page.getByRole('checkbox', { name: 'Photo moments' }).check();
  await page.getByRole('button', { name: 'Save preferences', exact: true }).click();
  await page.locator('.post-card').first().getByRole('button', { name: 'Share post', exact: true }).click();
  const send = page.waitForResponse(r => r.url().endsWith('/api/social') && r.request().method() === 'POST' && r.request().postDataJSON()?.action === 'message');
  await page.locator('.share-people button').first().click();
  expect((await send).status()).toBe(200);
  await expect(page.locator('[role="dialog"]')).toHaveCount(0);
  console.log('PASS: feed preferences and sharing a post into a conversation');
  await page.locator('.story').nth(1).click();
  await expect(page.locator('.story-viewer')).toBeVisible();
  await page.getByRole('button', { name: 'Next story', exact: true }).click();
  await expect(page.locator('.story-person')).toContainText('noah.creates');
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await page.locator('.mobile-nav').getByRole('button', { name: 'Create a post', exact: true }).click();
  await page.locator('input[type="file"]').setInputFiles('public/images/flowers.jpg');
  await expect(page.locator('.create-preview img')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await mkdir('artifacts', { recursive: true });
  await page.screenshot({ path: 'artifacts/mobile-final.png' });
  expect(errors).toEqual([]);
  console.log('PASS: story navigation, mobile upload preview, and no browser errors');
  console.log('ALL MOBILE AND DIALOG CHECKS PASSED');
} catch(e) {
  await page.screenshot({ path: 'artifacts/mobile-failure.png' }).catch(() => {});
  console.error(e); process.exitCode = 1;
} finally {
  await browser.close();
  if (chatIds.length) await db.delete(chats).where(inArray(chats.id, chatIds));
  if (id) await db.delete(users).where(eq(users.id, id));
  await pool.end();
  console.log('Mobile test data cleaned up.');
}
